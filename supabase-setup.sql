create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  gamer_tag text not null check (char_length(gamer_tag) between 1 and 20),
  game text not null default '',
  platform text not null default '',
  region text not null default '',
  created_at timestamptz not null default now()
);

create unique index if not exists profiles_gamer_tag_lower_unique
  on public.profiles (lower(gamer_tag));

create table if not exists public.direct_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 300),
  created_at timestamptz not null default now(),
  read_at timestamptz,
  constraint direct_messages_no_self_message check (sender_id <> recipient_id)
);

grant select, update on public.profiles to authenticated;
grant select, insert on public.direct_messages to authenticated;
grant update (read_at) on public.direct_messages to authenticated;
grant usage, select on sequence public.direct_messages_id_seq to authenticated;

create index if not exists direct_messages_sender_recipient_time
  on public.direct_messages (sender_id, recipient_id, created_at desc);

create index if not exists direct_messages_recipient_sender_time
  on public.direct_messages (recipient_id, sender_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.direct_messages enable row level security;

drop policy if exists "Authenticated users can view profiles" on public.profiles;
create policy "Authenticated users can view profiles"
  on public.profiles for select
  to authenticated
  using (true);

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
  on public.profiles for update
  to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

drop policy if exists "Users can read their direct messages" on public.direct_messages;
create policy "Users can read their direct messages"
  on public.direct_messages for select
  to authenticated
  using (sender_id = (select auth.uid()) or recipient_id = (select auth.uid()));

drop policy if exists "Users can send direct messages as themselves" on public.direct_messages;
create policy "Users can send direct messages as themselves"
  on public.direct_messages for insert
  to authenticated
  with check (
    sender_id = (select auth.uid())
    and recipient_id <> (select auth.uid())
    and exists (select 1 from public.profiles p where p.id = recipient_id)
  );

drop policy if exists "Recipients can mark messages as read" on public.direct_messages;
create policy "Recipients can mark messages as read"
  on public.direct_messages for update
  to authenticated
  using (recipient_id = (select auth.uid()))
  with check (recipient_id = (select auth.uid()));

create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, gamer_tag)
  values (
    new.id,
    left(coalesce(nullif(trim(new.raw_user_meta_data ->> 'gamer_tag'), ''), 'Player'), 20)
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
  after insert on auth.users
  for each row execute procedure public.create_profile_for_new_user();

insert into public.profiles (id, gamer_tag)
select
  u.id,
  left(coalesce(nullif(trim(u.raw_user_meta_data ->> 'gamer_tag'), ''), 'Player'), 20)
from auth.users u
on conflict (id) do nothing;

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    alter publication supabase_realtime add table public.direct_messages;
  end if;
exception
  when duplicate_object then null;
end;
$$;
